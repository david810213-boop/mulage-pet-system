-- V16：狗狗「基礎定制調理」「中階定制調理」開放線上預約（2026-09-06）
--
-- 背景：這兩個服務等級原本 bookable=false，LIFF 預約頁只看得到「精緻洗」
-- 跟「高階定制調理」。店家這次要求改成四個服務等級（精緻洗/基礎定制調理/
-- 中階定制調理/高階定制調理）都要能依體重+毛長篩選顯示，不限制服務等級。
--
-- 影響範圍：不分毛長（短毛/長毛/中長毛全部一起開放），因為篩選本來就是
-- 「體重+毛長」兩個條件決定顯示哪些項目，跟服務等級無關——如果只開放
-- 某個毛長的基礎/中階調理，會變成同一個體重級距下、不同毛長看到的服務
-- 等級選項不一樣，造成新的不一致，所以這次三種毛長一起處理。
--
-- 用 LIKE 依名稱裡的「基礎定制調理」/「中階定制調理」字樣比對，不用一個個
-- 列代碼——這兩個詞不像「長毛」那樣是其他詞的子字串，不會有 V13 那種
-- 誤判風險，可以放心用 LIKE。

UPDATE grooming_items
SET bookable = true
WHERE item_code LIKE 'DOG%'
  AND (name LIKE '%基礎定制調理%' OR name LIKE '%中階定制調理%')
  AND is_deleted = false;
